export function getTranslation(language, key) {
  const langKey = language === "hi" || language === "hi-IN" 
    ? "hi" 
    : language === "mr" || language === "mr-IN" 
      ? "mr" 
      : "en";

  const selectedLanguage = translations[langKey] || translations.en;
  return selectedLanguage[key] || translations.en[key] || key;
}

